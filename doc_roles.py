def role_for(series_dir, stem):
    """返回 (role_class, label, note) 或 None。规则按顺序，首个子串命中生效。"""
    for d, pat, role, label, note in RULES:
        if d == series_dir and pat in stem:
            return (role, label, note)
    return None
